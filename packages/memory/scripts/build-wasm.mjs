// Builds crates/memory for wasm32-unknown-unknown with simd128 and writes
// packages/memory/wasm/memory.wasm plus src/inline.ts (the same bytes as
// base64, for single file builds that run from file://).
// usage: node packages/memory/scripts/build-wasm.mjs
// Needs a rustc with the wasm32 standard library; set RUSTC to choose one
// (the owner's Mac: ~/.rustup/toolchains/stable-aarch64-apple-darwin/bin/rustc).
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const pkg = join(import.meta.dirname, "..");
const repo = join(pkg, "..", "..");
const rustup = join(homedir(), ".rustup/toolchains/stable-aarch64-apple-darwin/bin");
const env = {
  ...process.env,
  CARGO_PROFILE_RELEASE_OPT_LEVEL: "s",
  CARGO_PROFILE_RELEASE_STRIP: "true",
  CARGO_PROFILE_RELEASE_PANIC: "abort",
};
if (!env.RUSTC && existsSync(join(rustup, "rustc"))) {
  env.RUSTC = join(rustup, "rustc");
  env.PATH = `${rustup}:${env.PATH}`;
}
const r = spawnSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "-p", "hackbuild-memory"], {
  cwd: repo,
  env,
  stdio: "inherit",
});
if (r.status !== 0) process.exit(r.status ?? 1);
const bytes = readFileSync(join(repo, "target/wasm32-unknown-unknown/release/hackbuild_memory.wasm"));
writeFileSync(join(pkg, "wasm/memory.wasm"), bytes);
const b64 = bytes.toString("base64");
const lines = b64.match(/.{1,120}/g) ?? [];
writeFileSync(
  join(pkg, "src/inline.ts"),
  "// Generated by scripts/build-wasm.mjs from crates/memory. Do not edit.\n" +
    `/** The memory core wasm (${bytes.length} bytes) as base64, for loadCore({ base64 }). */\n` +
    "export const MEMORY_WASM_BASE64 =\n" +
    lines.map((l, i) => `  "${l}"${i < lines.length - 1 ? " +" : ";"}`).join("\n") +
    "\n",
);
console.log(`memory.wasm ${bytes.length} bytes`);
