// Builds a crate for wasm32-unknown-unknown with simd128 and writes
// packages/<pkg>/wasm/<pkg>.wasm plus packages/<pkg>/src/inline.ts (the
// same bytes as base64, for single file builds that run from file://).
// usage: node tools/build-wasm.mjs <crate dir> <package> <CONST_NAME>
//        node tools/build-wasm.mjs --all      every crate in CRATES
// e.g.   node tools/build-wasm.mjs audio-dsp audio-dsp AUDIO_DSP_WASM_BASE64
//
// The compiler is the rustup toolchain named in rust-toolchain.toml
// (1.95.0 with the wasm32 standard library), found with `rustup which`, so
// a Homebrew rustc earlier on PATH, which has no wasm32 std, is not used.
// Set RUSTC to override. CI runs --all and then git diff --exit-code.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export const CRATES = [
  ["memory", "memory", "MEMORY_WASM_BASE64"],
  ["character", "character", "CHARACTER_WASM_BASE64"],
  ["audio-dsp", "audio-dsp", "AUDIO_DSP_WASM_BASE64"],
  ["depth-mesh", "depth-mesh", "DEPTH_MESH_WASM_BASE64"],
  ["biosignal", "biosignal", "BIOSIGNAL_WASM_BASE64"],
];

const repo = join(import.meta.dirname, "..");
const channel = /^channel\s*=\s*"([^"]+)"/m.exec(readFileSync(join(repo, "rust-toolchain.toml"), "utf8"))[1];
const env = { ...process.env, CARGO_PROFILE_RELEASE_OPT_LEVEL: "s", CARGO_PROFILE_RELEASE_STRIP: "true", CARGO_PROFILE_RELEASE_PANIC: "abort" };
if (!env.RUSTC) {
  const w = spawnSync("rustup", ["which", "rustc", "--toolchain", channel], { encoding: "utf8" });
  if (w.status === 0 && w.stdout.trim()) {
    env.RUSTC = w.stdout.trim();
    env.PATH = `${dirname(env.RUSTC)}:${env.PATH}`;
  } else console.warn(`rustup has no ${channel} toolchain; using the rustc on PATH, whose wasm may differ`);
}

function build(crate, pkgName, constName) {
  const pkg = join(repo, "packages", pkgName);
  const meta = readFileSync(join(repo, "crates", crate, "Cargo.toml"), "utf8");
  const name = /^name\s*=\s*"([^"]+)"/m.exec(meta)[1];
  const r = spawnSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "-p", name], { cwd: repo, env, stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
  const bytes = readFileSync(join(repo, "target/wasm32-unknown-unknown/release", `${name.replace(/-/g, "_")}.wasm`));
  mkdirSync(join(pkg, "wasm"), { recursive: true });
  writeFileSync(join(pkg, "wasm", `${pkgName}.wasm`), bytes);
  const lines = bytes.toString("base64").match(/.{1,120}/g) ?? [];
  writeFileSync(
    join(pkg, "src/inline.ts"),
    `// Generated by tools/build-wasm.mjs from crates/${crate} with rustc ${channel}. Do not edit.\n` +
      `/** The ${crate} core wasm (${bytes.length} bytes) as base64. */\n` +
      `export const ${constName} =\n` +
      lines.map((l, i) => `  "${l}"${i < lines.length - 1 ? " +" : ";"}`).join("\n") +
      "\n",
  );
  console.log(`${pkgName}.wasm ${bytes.length} bytes`);
}

const args = process.argv.slice(2);
if (args[0] === "--all") for (const c of CRATES) build(...c);
else {
  const [crate, pkgName, constName] = args;
  if (!crate || !pkgName || !constName) {
    console.error("usage: node tools/build-wasm.mjs <crate dir> <package> <CONST_NAME> | --all");
    process.exit(2);
  }
  build(crate, pkgName, constName);
}
