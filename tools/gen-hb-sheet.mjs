// gen-hb-sheet: writes packages/ai-elements/src/hb-sheet.ts from the
// vendored hackbuild-ui class layer (tools/vendor, pinned by commit). The
// elements adopt this CSS into each shadow root. Two changes make it work
// there without hackbuild-ui on the page:
//   - every var(--hb-x) gains a fallback holding the hackbuild-ui value, so
//     tokens a page sets on the element or any ancestor reach in, and an
//     element on a bare page still gets the hackbuild-ui look;
//   - page level rules become :host rules (body.hb, the .hb scope), the
//     @import of tokens.css and the page grain overlay go, comments go;
//   - only rules the elements can match stay: a selector naming an hb-
//     class that no element source (packages/ai-elements/src) writes goes,
//     and so do @keyframes no kept rule animates with. Element, :host and
//     state class (is-) selectors stay. npm run build reruns this, so the
//     subset follows the templates.
// Usage: node tools/gen-hb-sheet.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const pkgPath = join(root, "node_modules", "@virgilvox", "hackbuild-ui", "package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
const styles = join(dirname(pkgPath), "dist", "styles");
const out = join(root, "packages", "ai-elements", "src", "hb-sheet.ts");
const vendor = readFileSync(join(root, "tools", "vendor", "SHA256SUMS"), "utf8").trim().split(/\s+/).pop();

const strip = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");

// tokens: the :root block of tokens.css, in order
const tokenCss = strip(readFileSync(join(styles, "tokens.css"), "utf8"));
const tokens = {};
for (const m of tokenCss.matchAll(/(--hb-[a-z0-9-]+)\s*:\s*([^;]+);/g)) tokens[m[1]] = m[2].trim().replace(/\s+/g, " ");

// var(--hb-x) without a fallback gets one, nested for tokens built from tokens
const withFallbacks = (css, depth = 0) =>
  css.replace(/var\((--hb-[a-z0-9-]+)\)/g, (all, name) => {
    if (!(name in tokens)) return all;
    if (depth > 4) throw new Error(`gen-hb-sheet: ${name} nests too deep`);
    return `var(${name}, ${withFallbacks(tokens[name], depth + 1)})`;
  });

let css = strip(readFileSync(join(styles, "hackbuild.css"), "utf8"));
css = css.replace(/@import[^;]+;/g, "");
// a :root block in the class layer holds more tokens: they join the fallbacks, and the block goes, as no shadow root matches :root
css = css.replace(/:root\s*\{([^}]*)\}/g, (_, decl) => {
  for (const m of decl.matchAll(/(--hb-[a-z0-9-]+)\s*:\s*([^;]+);?/g)) tokens[m[1]] = m[2].trim().replace(/\s+/g, " ");
  return "";
});
css = css.replace(/body\.hb::before\s*\{[^}]*\}/g, "");
css = css.replace(/html,body\{[^}]*\}/g, "");
css = css.replace(/body\.hb\b/g, ":host");
css = css.replace(/(^|[\s,{(])\.hb(?=\s)/g, "$1:host");
css = withFallbacks(css);

// subset: hb- classes the element sources name anywhere (templates, state maps, HOST_CSS)
const srcDir = join(root, "packages", "ai-elements", "src");
const used = new Set();
for (const f of readdirSync(srcDir)) {
  if (!f.endsWith(".ts") || f === "hb-sheet.ts") continue;
  for (const m of readFileSync(join(srcDir, f), "utf8").matchAll(/hb-[a-z0-9-]*[a-z0-9]/g)) used.add(m[0]);
}
const keepSelector = (sel) => [...sel.matchAll(/\.(hb-[a-z0-9-]+)/g)].every((m) => used.has(m[1]));
// split a css text into top level items: [prelude, block] pairs
function items(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    let depth = 1, j = open + 1;
    while (depth && j < text.length) depth += text[j] === "{" ? 1 : text[j] === "}" ? -1 : 0, j++;
    out.push([text.slice(i, open).trim(), text.slice(open + 1, j - 1)]);
    i = j;
  }
  return out;
}
function subset(text) {
  let kept = "";
  for (const [pre, block] of items(text)) {
    if (pre.startsWith("@keyframes")) { kept += `${pre}{${block}}\n`; continue; }
    if (pre.startsWith("@")) { const inner = subset(block); if (inner.trim()) kept += `${pre}{ ${inner} }\n`; continue; }
    const sels = pre.split(/,(?![^(]*\))/).map((x) => x.trim()).filter(keepSelector);
    if (sels.length) kept += `${sels.join(",")}{${block}}\n`;
  }
  return kept;
}
const full = css.length;
css = subset(css);
// keyframes stay only when a kept rule names them
const rest = css.replace(/@keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, "");
css = css.replace(/@keyframes\s+([\w-]+)\s*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}\n?/g, (all, name) => (new RegExp(`\\b${name}\\b`).test(rest) ? all : ""));
css = css
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean)
  .join("\n");
if (/@import|body\.hb|(^|[\s,])\.hb\s/m.test(css)) throw new Error("gen-hb-sheet: a page level rule survived");

const body = `// Generated by tools/gen-hb-sheet.mjs from ${pkg.name} ${pkg.version}
// (tools/vendor/${vendor}). Do not edit; rerun the tool.

/** hackbuild-ui token defaults, the values the elements fall back to. */
export const TOKENS: Readonly<Record<string, string>> = ${JSON.stringify(tokens, null, 2)};

/** The hackbuild-ui class layer rules the elements use, rewritten for a shadow root. */
export const HB_CSS: string = ${JSON.stringify(css)};
`;

if (process.argv.includes("--check")) {
  const now = readFileSync(out, "utf8");
  if (now !== body) {
    console.error("gen-hb-sheet: packages/ai-elements/src/hb-sheet.ts is stale; run node tools/gen-hb-sheet.mjs");
    process.exit(1);
  }
  console.log("gen-hb-sheet: up to date");
} else {
  writeFileSync(out, body);
  console.log(`gen-hb-sheet: ${Object.keys(tokens).length} tokens, ${(css.length / 1024).toFixed(1)} KB of css, ${used.size} hb- names kept from ${(full / 1024).toFixed(1)} KB`);
}
